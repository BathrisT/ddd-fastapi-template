"""Реестр задач очереди: список обработчиков. Единственный список входов очереди.

Регистрация — явная операция, а не побочный эффект импорта (правило 8
композиции). Набор
import-строк в точках входа, ведущийся руками, расходится молча: в воркере один
список, в шедулере другой, и забытая строка даёт не ошибку сборки, а отказ в
проде при первом обращении.

Имя задачи — имя самой функции-обработчика. Отдельного словаря имён нет
намеренно: от забывчивости он не страхует (строку в реестре пишешь тем же
движением, что и имя), зато заставляет вести параллельный список.

**Ретраев нет ни у одной задачи, и это решение, а не упущение.** Повторять
можно только идемпотентную работу: отправка наружу, платное обращение к модели
и обмен одноразового токена повтора не переживут. `max_retries` в реестре без
включённого `SimpleRetryMiddleware` и метки `retry_on_error` не делает вообще
ничего — это документация несуществующей гарантии. Включать middleware можно
только после того, как каждая задача станет идемпотентной поимённо.

Ещё одно следствие: **имя задачи едет в Redis внутри уже поставленных
сообщений**. Переименование функции-обработчика меняет проводное имя, и
сообщения, лежащие в очереди в момент деплоя, свою задачу не найдут.
"""

from collections.abc import Callable
from typing import Any

from dishka.integrations.taskiq import inject
from taskiq import AsyncBroker

from app.interface.worker.handlers import users


class WorkerTasks:
    TABLE: list[Callable[..., Any]] = [
        # ── По событию или по требованию ──────────────────────────
        users.welcome_user,
        # ── По расписанию ─────────────────────────────────────────
        users.purge_inactive_users,
    ]

    @staticmethod
    def register(broker: AsyncBroker) -> None:
        """Повесить обработчики на брокер. Зовётся каждой точкой входа очереди."""
        for handler in WorkerTasks.TABLE:
            broker.register_task(inject(handler, patch_module=True), task_name=handler.__name__)
