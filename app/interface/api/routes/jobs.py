"""Опрос исхода фоновой задачи: длинная операция с прогрессом в UI.

Маршрут закрыт гейтом. Идентификатор задачи неугадываем, но неугадываемость —
не право доступа: он уезжает в историю браузера, в `Referer`, в лог nginx и в
Sentry вместе с URL запроса. Ключ, проверяемый отдельно, делает утёкшую ссылку
бесполезной.

**Владельца задачи здесь никто не проверяет, и это дыра, оставленная
сознательно.** В шаблоне звонящий один на приложение, сверять не с чем. Как
только их станет несколько — арендаторы, пользователи, внешние системы, —
проверка встаёт ровно сюда: «эта задача поставлена этим звонящим?», а
`Caller` уже приходит в хендлер. Без неё ручка отдаёт результат любой задачи
любому, у кого есть ключ, а `JobOutcome.result` — это `dict[str, object]`, то
есть что угодно, что положила туда любая будущая задача.

Порт `JobResults` берётся напрямую, без сценария, и это осознанно: тут нет ни
правила, ни транзакции — только пересказ состояния очереди. Заворачивать это в
`*UseCase` значило бы завести сценарий, у которого нет своего решения.

**`success` значит «задача завершилась», а не «эта задача сделала работу».**
Разница видна, когда две задачи просят одно и то же: вторая упирается в замок,
выходит без исключения, и очередь отмечает её успешной, пока первая ещё идёт в
модель. Клиент, опрашивающий вторую, закроет прогресс раньше времени и не
узнает, если первая упадёт.

В шаблоне цена этому нулевая: обработчики результата не возвращают вовсе, и
`result` всегда пустой. Появится задача, чей результат читают, — различать
придётся здесь: отдельным статусом «работу делает другая задача» либо
дедупликацией на постановке, чтобы второй номер не выдавался вовсе.
"""

from dishka import FromDishka
from dishka.integrations.fastapi import DishkaRoute
from fastapi import APIRouter

from app.application.ports.job_results import JobResults
from app.interface.api.guards.api_key import CallerDep
from app.interface.api.schemas.job import JobResponse

router = APIRouter(prefix="/jobs", tags=["jobs"], route_class=DishkaRoute)


@router.get("/{job_id}")
async def get_job(job_id: str, _: CallerDep, results: FromDishka[JobResults]) -> JobResponse:
    outcome = await results.get(job_id)
    return JobResponse(status=outcome.status, result=outcome.result, error=outcome.error)
