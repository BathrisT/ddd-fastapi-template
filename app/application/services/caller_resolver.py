"""Общая половина проверки входа: предъявленное → опознанный звонящий.

Правило composition делит проверку надвое, и деление это не формальное:

* **проверка транспортная** — достать доказательство оттуда, где оно у этого
  входа лежит. У HTTP это заголовок, у очереди — поле `message.kwargs`, у
  следующего протокола будет своё. Она обязана быть у каждого входа своя и
  живёт во входе;
* **резолюция общая** — превратить доказательство в личность. Одинакова для
  всех входов, и живёт здесь.

Оставь резолюцию в HTTP-гейте — и второй вход либо продублирует её, либо
начнёт звать гейт оттуда, где нет `Request`. Именно поэтому вход не имеет права
брать репозиторий (`scripts/check_composition.py`): всё, что нужно достать,
достаёт application.

**Проверка тут намеренно тривиальная — сравнение с ключом из настроек.**
Это шов, а не система аутентификации: у настоящего проекта здесь будет разбор
JWT, поход в каталог пользователей или обращение к внешнему провайдеру. Меняется
ТЕЛО этого метода; форма вокруг — гейт, `Caller`, отказ `AuthError` — остаётся.
"""

from loguru import logger

from app.application.dto.caller import Caller
from app.domain.exceptions import AuthError


class CallerResolver:
    def __init__(self, expected_key: str) -> None:
        self._expected = expected_key

    def resolve(self, presented: str | None) -> Caller:
        """Опознать звонящего или отказать.

        Пустой ключ в настройках — вход не проверяется. Шаблон обязан
        подниматься из коробки, но молча пропускать при этом нельзя: незакрытые
        ручки в проде выглядят точно так же, как работающие, и узнают о них
        последними. Поэтому каждый такой пропуск пишется в лог.
        """
        if not self._expected:
            logger.warning("caller_resolver: APP__API_KEY пуст — запрос пропущен без проверки")
            return Caller(name="anonymous")

        # Сравнение обычное, а не постоянного времени: ключ высокоэнтропийный,
        # и утечка по времени сравнения дала бы атакующему знание о префиксе
        # там, где перебор всё равно невозможен. Появится ключ, выводимый из
        # пароля, — сравнение придётся менять вместе с ним.
        if presented != self._expected:
            raise AuthError("Неверный ключ доступа")

        return Caller(name="service")
