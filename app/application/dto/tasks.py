"""Намерения: «сделай вот это в фоне». По одному на вид работы.

Тот же приём, что у доменных событий, и по той же причине: сценарий обязан
назвать, ЧЕГО он хочет, не называя, кто это исполнит. Имя обработчика — знание
входного слоя, и `application` его не видит.

Отличие от события — в том, кто чего ждёт. Событие говорит «случилось» и
уходит; намерение говорит «сделай», и отправитель ждёт номер, чтобы опросить
исход.

Новое намерение заводится здесь, а ветка для него — в
`composition/task_router.py`. Забыть ветку нельзя молча: маршрутизатор
отказывает вслух, потому что вызывающий держит в руках несуществующий номер.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class TaskIntent:
    """База намерений — чтобы порт не принимал что попало."""


@dataclass(frozen=True)
class WelcomeUser(TaskIntent):
    user_id: int
