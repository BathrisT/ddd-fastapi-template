"""Чем кончилось приветствие — чтобы опрашивающий видел разницу.

Сценарий заканчивается четырьмя разными способами, и три из них — не «сделал».
Пока обработчик возвращал `None`, очередь отмечала успехом все четыре: клиент,
опрашивающий `/jobs/{id}`, закрывал прогресс на «готово» там, где работу
делал кто-то другой или не делал никто.

`status` строкой, а не енумом, — как у `JobOutcome.status` рядом: значения
уезжают в JSON, и лишний слой преобразования на границе ничего не добавляет.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class WelcomeOutcome:
    # welcomed — сходили в модель и сохранили
    # already   — приветствие уже было, повторно не платили
    # busy      — этим занят другой прогон, замок не отдали
    # gone      — пользователя больше нет
    status: str
    message: str | None = None
