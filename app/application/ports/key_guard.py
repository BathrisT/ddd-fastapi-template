"""Порт «занять ключ на время» — межпроцессный сторож.

Занять, если свободен, и освободить СВОЙ захват. На этом строятся и лок
прогона («прошлый ещё идёт — пропускаем тик»), и гард постановки («это
срабатывание уже поставлено в очередь»).

Нужен потому, что оба сторожа — механика координации процессов, а не бизнес, и
в сценарии обязаны приходить портом: сценарий не должен знать, что за
координацией стоит Redis.

`claim` возвращает не `bool`, а токен владения, и это не украшение. Захват
живёт ограниченное время: работа, не уложившаяся в TTL, теряет ключ, его
занимает следующий, и тогда безусловное освобождение сносит ЧУЖОЙ захват —
дальше замок не держит вообще никого. Токен делает освобождение проверяемым.
"""

from typing import Protocol


class KeyGuard(Protocol):
    async def claim(self, key: str, ttl_seconds: int) -> str | None:
        """Занять ключ на ttl. Токен владения или `None`, если ключ уже занят."""
        ...

    async def release(self, key: str, token: str) -> None:
        """Освободить СВОЙ захват. Чужой не трогает: если ключ уже перезанят
        (наша работа не уложилась в TTL), вызов ничего не делает."""
        ...
