"""Отправить работу в фон и получить её номер — общий порт на все задачи.

Парный к `EventPublisher`, и разница между ними смысловая, а не техническая:

* **событие** — «случилось». Отправитель не ждёт ничего и не знает, во что оно
  превратится: сегодня в одну задачу, завтра в три. Номера у него поэтому нет;
* **задача** — «сделай». Отправитель ждёт исхода: у него в UI крутится
  прогресс, и по номеру он опрашивает `JobResults`.

Почему порт, а не прямой `TaskQueue.enqueue`: тот просит ИМЯ обработчика, а
обработчики живут в `interface/worker/handlers/`, куда `application` заглядывать
не имеет права (`tach`). Сценарий называет НАМЕРЕНИЕ — объект из
`application/dto/tasks.py`, — а какой обработчик за ним стоит, знает
композиция.

Ровно поэтому здесь один порт на все задачи, а не по порту на каждую: намерений
будет много, а шов между `application` и обработчиками — один.
"""

