"""Пользователь — и демонстрационная сущность шаблона, и то, что почти наверняка
останется в проекте.

На ней видно шов: одна и та же вещь проходит все слои — доменная модель, порт
репозитория, сценарий, событие, обработчик очереди, строка расписания. Что из
неё не нужно (например, приветствие от модели), удаляют по следу
`rg -l welcome app tests migrations`.
"""

from dataclasses import dataclass
from datetime import datetime

from app.domain.exceptions import ValidationError


@dataclass
class User:
    # `0` — «ещё не сохранён»: развилку «вставить или обновить» держит
    # репозиторий, и она у всех сущностей одна (CLAUDE.md, «Идентификаторы»).
    # Значение по умолчанию тут не стоит намеренно — заводя сущность, автор
    # обязан сказать `id=0` вслух, иначе несохранённое и сохранённое выглядят
    # на месте вызова одинаково.
    id: int
    email: str
    name: str
    # Неактивный — тот, кто зарегистрировался и не подтвердил почту. Уборка по
    # расписанию сносит именно таких, и только их: активного пользователя не
    # удаляет ничто автоматическое.
    is_active: bool = False
    # `None` до первого сохранения: момент ставит база, а не приложение.
    created_at: datetime | None = None
    # Пишется фоновой задачей после регистрации — до неё `None`, и это
    # нормальное состояние, а не ошибка: сценарий регистрации модель не ждёт.
    welcome_message: str | None = None

    @staticmethod
    def register(email: str, name: str) -> "User":
        """Завести пользователя, приведя его к виду, в котором он валиден.

        Правила заведения живут ЗДЕСЬ, а не в сценарии регистрации, и это тот
        шов, ради которого домен вообще существует. Нормализация почты — не
        косметика: сохранив «Ann@», а поискав «ann@», получаешь двух человек
        вместо одного, и уникальный индекс этого не поймает — для базы это
        разные строки.

        Оставь правило в сценарии — и второй вход, заводящий пользователя
        (импорт из файла, админка, задача очереди), заведёт его мимо правила.
        Забыть можно то, что можно обойти; метод сущности обойти нельзя, не
        написав `User(...)` руками.

        Инвариант, не принадлежащий ни одной сущности, живёт в
        `domain/services/`, а общее значение — в `domain/catalog/policy.py`.
        """
        cleaned = name.strip()
        if not cleaned:
            raise ValidationError("Имя не может быть пустым")
        return User(id=0, email=email.strip().lower(), name=cleaned)
